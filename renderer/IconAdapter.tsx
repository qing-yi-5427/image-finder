const compactNames = Object.fromEntries(
  Object.entries(iconByName).map(([name, icon]) => [
    name.replace(/-/g, ""),
    icon,
  ]),
) as Record<string, LucideIcon>;

export function Icon({ name, size = 16 }: { name: string; size?: number }) {
  const normalized = name.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();
  const Glyph =
    iconByName[normalized] ??
    compactNames[normalized.replace(/-/g, "")] ??
    CircleHelp;
  return (
    <span
      className="if-icon"
      style={{ width: size, height: size }}
      aria-hidden="true"
    >
      <Glyph
        size={size}
        strokeWidth={1.65}
        aria-hidden="true"
        focusable="false"
      />
    </span>
  );
}
